// Installs optional local git hooks by generating them into the repository's
// .git/hooks directory. The hook scripts are NOT tracked in the repository
// tree, so they never get pushed (some upstream rulesets forbid committing
// pre-commit / pre-push hook scripts). CI remains the authoritative gate.
//
// Enable with:  pnpm run hooks:install
// Disable with: pnpm run hooks:uninstall
import { execFileSync } from 'node:child_process';
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** Hook name -> command executed by that hook. */
const HOOKS = {
  'pre-commit': 'pnpm exec lint-staged',
  'pre-push': 'pnpm run typecheck && pnpm run check:i18n',
};

function resolveHooksDir() {
  const out = execFileSync('git', ['rev-parse', '--git-path', 'hooks'], {
    encoding: 'utf8',
  }).trim();
  return out;
}

function buildHookScript(command) {
  return [
    '#!/usr/bin/env sh',
    '# AUTO-GENERATED by scripts/install-git-hooks.mjs — do not edit.',
    '# This is a local convenience only; CI is the authoritative gate.',
    '# Skip a single run with --no-verify. Remove with: pnpm run hooks:uninstall',
    '',
    command,
    '',
  ].join('\n');
}

// Clear any previous override (e.g. an earlier core.hooksPath=.githooks setup)
// BEFORE resolving the hooks directory, otherwise `git rev-parse --git-path
// hooks` would return the overridden path instead of the default .git/hooks.
try {
  execFileSync('git', ['config', '--unset', 'core.hooksPath'], {
    stdio: 'ignore',
  });
} catch {
  // No override was set; nothing to clear.
}

const hooksDir = resolveHooksDir();
mkdirSync(hooksDir, { recursive: true });

for (const [name, command] of Object.entries(HOOKS)) {
  const file = join(hooksDir, name);
  writeFileSync(file, buildHookScript(command), { mode: 0o755 });
  try {
    chmodSync(file, 0o755);
  } catch {
    // chmod is a no-op / may fail on Windows; the hook still runs via sh.
  }
}

console.log(`Local git hooks installed into ${hooksDir}`);
console.log(`  - ${Object.keys(HOOKS).join(', ')}`);
